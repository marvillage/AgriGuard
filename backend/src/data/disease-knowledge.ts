export type Language = "en" | "hi" | "mr" | "pa" | "te" | "ta";

export interface DiseaseText {
  name: string;
  symptoms: string[];
  actions: string[];
  prevention: string[];
}

export interface DiseaseInfo {
  label: string;
  crop: string;
  cropKey: string;
  healthy: boolean;
  pathogen: string | null;
  kind: "fungal" | "bacterial" | "viral" | "oomycete" | "pest" | "healthy";
  spreadRisk: "low" | "medium" | "high";
  text: Record<Language, DiseaseText>;
}

type Phrase = Record<Language, string>;

interface DiseaseSpec {
  label: string;
  crop: string;
  cropKey: string;
  pathogen: string;
  kind: Exclude<DiseaseInfo["kind"], "healthy">;
  spreadRisk: DiseaseInfo["spreadRisk"];
  name: Phrase;
  symptoms: Phrase[];
  actions: Phrase[];
  prevention: Phrase[];
}

const languages: Language[] = ["en", "hi", "mr", "pa", "te", "ta"];

const orWord: Phrase = { en: "or", hi: "या", mr: "किंवा", pa: "ਜਾਂ", te: "లేదా", ta: "அல்லது" };

function chem(en: string, hi: string, mr: string, pa: string, te: string, ta: string): Phrase {
  return {
    en,
    hi: `${hi} (${en})`,
    mr: `${mr} (${en})`,
    pa: `${pa} (${en})`,
    te: `${te} (${en})`,
    ta: `${ta} (${en})`,
  };
}

function joinOr(items: string[], word: string): string {
  if (items.length < 2) return items.join("");
  return `${items.slice(0, -1).join(", ")} ${word} ${items[items.length - 1]}`;
}

function spray(when: Phrase, chemicals: Phrase[]): Phrase {
  const list = (language: Language) => joinOr(chemicals.map((item) => item[language]), orWord[language]);
  return {
    en: `${when.en}, spray ${list("en")}.`,
    hi: `${when.hi} ${list("hi")} का छिड़काव करें।`,
    mr: `${when.mr} ${list("mr")} यापैकी एकाची फवारणी करा.`,
    pa: `${when.pa} ${list("pa")} ਦਾ ਛਿੜਕਾਅ ਕਰੋ।`,
    te: `${when.te} ${list("te")} పిచికారీ చేయండి.`,
    ta: `${when.ta} ${list("ta")} தெளிக்கவும்.`,
  };
}

function texts(name: Phrase, symptoms: Phrase[], actions: Phrase[], prevention: Phrase[]): Record<Language, DiseaseText> {
  const pairs = languages.map((language): [Language, DiseaseText] => [
    language,
    {
      name: name[language],
      symptoms: symptoms.map((item) => item[language]),
      actions: actions.map((item) => item[language]),
      prevention: prevention.map((item) => item[language]),
    },
  ]);
  return Object.fromEntries(pairs) as Record<Language, DiseaseText>;
}

